#!/usr/bin/env python3
"""Generate private wrapping ranges from the checked-in Unicode 18 inputs."""

from pathlib import Path


def properties(path):
    result = {}
    for row in path.read_text(encoding="utf-8").splitlines():
        row = row.split("#", 1)[0].strip()
        if not row:
            continue
        span, name = map(str.strip, row.split(";"))
        ends = span.split("..")
        first, last = int(ends[0], 16), int(ends[-1], 16)
        result.setdefault(name, set()).update(range(first, last + 1))
    return result


def ranges(points):
    start = last = None
    for point in sorted(points):
        if last is not None and point != last + 1:
            yield start, last
            start = None
        if start is None:
            start = point
        last = point
    if start is not None:
        yield start, last


root = Path(__file__).resolve().parent
props = properties(root / "PropList.txt")
punctuation = set()
for row in (root / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
    point, _, category, *_ = row.split(";")
    if category.startswith("P") and category != "Ps":
        punctuation.add(int(point, 16))
punctuation -= props["Quotation_Mark"]

lines = [
    "// Generated by support/unicode/gen-wrap-tables.py; Unicode 18.0.0.",
    "// Unicode data: see support/unicode/LICENSE-Unicode.txt.",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace tjg::color::detail {",
    "",
    "struct wrap_range { std::uint32_t first, last; };",
]
for name, points in (("wrap_spaces", props["White_Space"]),
                     ("wrap_punctuation", punctuation)):
    lines += ["", f"inline constexpr wrap_range {name}[] = {{"]
    lines += [f"  {{0x{first:04x}, 0x{last:04x}}},"
              for first, last in ranges(points)]
    lines += ["};"]
lines += ["", "} // tjg::color::detail", ""]
(root.parent.parent / "src/WrapData.hpp").write_text(
    "\n".join(lines), encoding="utf-8", newline="\n")
